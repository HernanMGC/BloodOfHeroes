DEFINE_LOG_CATEGORY(LogBOHPathActor);

////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////

FBOHUnitPath::FBOHUnitPath() : UnitPtr(nullptr), UnitMoves(TArray<FVector>())
{
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

FBOHUnitPath::FBOHUnitPath(ABOHUnit* InUnitPtr, TArray<FVector> InUnitMoves) : UnitPtr(InUnitPtr), UnitMoves(InUnitMoves)
{
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

bool FBOHUnitPath::operator==(const FBOHUnitPath& Other) const
{
	return UnitPtr == Other.UnitPtr
	&& UnitMoves == Other.UnitMoves;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

bool FBOHUnitPath::IsValid() const
{
	return UnitPtr != nullptr;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

FString FBOHUnitPath::ToString() const
{
	FString Str = FString("");
	for (int i = 0; i < UnitMoves.Num(); i++)
	{
		if (!UnitPtr)
		{
			BOH_LOG(LogBOHPathActor, Error, "Invalid Unit Pointer");
		}
		
		int32 UnitID = UnitPtr ? UnitPtr->GetUnitInfo().UnitID : INDEX_NONE;
		Str.Append(FString::Printf(TEXT("[UnitID:%d][%d] moves to %s"), UnitID , i, *UnitMoves[i].ToString()));

		if (i < UnitMoves.Num() -1)
		{
			Str.Append(FString("\n\t"));
		}
	}

	return Str;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

ABOHPathActor::ABOHPathActor()
{
	PrimaryActorTick.bCanEverTick = false;
	
	RootComponent = CreateDefaultSubobject<USceneComponent>(TEXT("RootComponent"));
	
	StaticMeshComponent = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("StaticMesh"));
	StaticMeshComponent->SetupAttachment(RootComponent);
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

ABOHUnit* ABOHPathActor::GetOwnerUnit()
{
	return Cast<ABOHUnit>(GetOwner());
}

////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////

void ABOHPathActor::OnConstruction(const FTransform& Transform)
{
	Super::OnConstruction(Transform);
	
	FVector Scale = FVector(1.f);
	Scale.Y = ActorSize;
	Scale.X = ActorSize;
	SetMeshSize(Scale);
}

////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////

void ABOHPathActor::SetIsPathActorSelected(bool bInIsPathActorSelected)
{
	bIsPathActorSelected = bInIsPathActorSelected;
	OnIsPathActorSelectedChanged(bInIsPathActorSelected);
}

////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////

void ABOHPathActor::SetMeshSize(const FVector& InScale3D) const
{
	StaticMeshComponent->SetWorldScale3D(InScale3D);
}

void ABOHPathActor::BeginPlay()
{
	Super::BeginPlay();
}

