//////////////////////////////////////////////////////////////////////////

UBOHAttributeSet::UBOHAttributeSet()
{
}

//////////////////////////////////////////////////////////////////////////
// 
//////////////////////////////////////////////////////////////////////////

UWorld* UBOHAttributeSet::GetWorld() const
{
	const UObject* outer = GetOuter();
	check(outer);

	return outer->GetWorld();
}

//////////////////////////////////////////////////////////////////////////
// 
//////////////////////////////////////////////////////////////////////////

UBOHAbilitySystemComponent* UBOHAttributeSet::GetBOHAbilitySystemComponent() const
{
	return Cast<UBOHAbilitySystemComponent>(GetOwningAbilitySystemComponent());
}