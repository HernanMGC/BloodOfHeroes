#include "BOHLogSettings.h"

//////////////////////////////////////////////////////////////////////////
// BOH::Log
//////////////////////////////////////////////////////////////////////////

namespace BOH::Log
{
	static int32 ShouldLogNetMode = 0;
	static FAutoConsoleVariableRef CVarLogNetMode
	(
		TEXT("BOH.Log.LogNetMode"),
		ShouldLogNetMode,
		TEXT("When using BOH_LOG macros, should we log the world context net mode?"),
		ECVF_Default | ECVF_Preview
	);

	static int32 ShouldLogFunction = 1;
	static FAutoConsoleVariableRef CVarLogFunction
	(
		TEXT("BOH.Log.LogFunction"),
		ShouldLogFunction,
		TEXT("When using BOH_LOG macros, should we log the function being logged from?"),
		ECVF_Default | ECVF_Preview
	);
}

//////////////////////////////////////////////////////////////////////////
// UBOHLogSettings
//////////////////////////////////////////////////////////////////////////

bool UBOHLogSettings::GetLogNetMode()
{
	return BOH::Log::CVarLogNetMode->GetBool();
}

//////////////////////////////////////////////////////////////////////////
// 
//////////////////////////////////////////////////////////////////////////

bool UBOHLogSettings::GetLogFunction()
{
	return BOH::Log::CVarLogFunction->GetBool();
}

