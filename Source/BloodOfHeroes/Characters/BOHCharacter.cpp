////////////////////////////////////////////////////////////////////////////////////
// FBOHUnitInfo
////////////////////////////////////////////////////////////////////////////////////

FBOHUnitInfo::FBOHUnitInfo(): UnitID(-1), TeamID(-1), UnitType(EBOHUnitType::None)
{
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

FBOHUnitInfo::FBOHUnitInfo(int32 InUnitID, int32 InTeamID, EBOHUnitType InUnitType) : UnitID(InUnitID),
	TeamID(InTeamID), UnitType(InUnitType)
{
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

bool FBOHUnitInfo::operator==(const FBOHUnitInfo& Other) const
{
	return Other.UnitID == UnitID
		&& Other.TeamID == TeamID
		&& Other.UnitType == UnitType;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

bool FBOHUnitInfo::IsValid() const
{
	return UnitID != -1
		&& TeamID != -1
		&& UnitType != EBOHUnitType::None
		&& UnitType != EBOHUnitType::MAX;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

FString FBOHUnitInfo::ToString() const
{
	return FString::Printf(
		TEXT("UnitID: %d - TeamID: %d - UnitType: %s"), UnitID, TeamID, *UEnum::GetValueAsString(UnitType));
}

////////////////////////////////////////////////////////////////////////////////////
// ABOHCharacter
////////////////////////////////////////////////////////////////////////////////////

ABOHCharacter::ABOHCharacter()
{
	PrimaryActorTick.bCanEverTick = false;
	PrimaryActorTick.bAllowTickOnDedicatedServer = false;
	PrimaryActorTick.bStartWithTickEnabled = false;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void ABOHCharacter::SetIsUnitSelected(bool bNewIsSelected)
{
	bIsUnitSelected = bNewIsSelected;
	OnUnitIsSelectedChanged.Broadcast(bIsUnitSelected);
}

