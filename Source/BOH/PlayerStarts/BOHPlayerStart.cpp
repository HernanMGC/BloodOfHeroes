ABOHPlayerStart::ABOHPlayerStart(const FObjectInitializer& ObjectInitializer)
	: Super(ObjectInitializer)
{
	PrimaryActorTick.bCanEverTick = false;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void ABOHPlayerStart::PostLoad()
{
	Super::PostLoad();

	if (UnitSpawnPoints.IsEmpty() && UnitPerPlayerStart > 0)
	{
		if (UnitPerPlayerStart == 1)
		{
			UnitSpawnPoints.Add(FVector(0.f));
			return;
		}

		for (int32 i = 0; i < UnitPerPlayerStart; i++)
		{
			UnitSpawnPoints.Add(FVector(
				0.f,
				(StartingLineMaxDistance * i / (UnitPerPlayerStart - 1)) - (StartingLineMaxDistance / 2),
				0.f
				)
			);
		}
	}
}

