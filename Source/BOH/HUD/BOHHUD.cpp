void ABOHHUD::BeginPlay()
{
	Super::BeginPlay();

	HUDWidget = CreateWidget<UBOHHudWidget>(GetOwningPlayerController(), HUDWidgetClass, TEXT("HUD"));
	if (!HUDWidget)
	{
		return;
	}
	HUDWidget->AddToViewport(0);
}

