#include "BOHVMPlayerUnits.h"

// BOH
#include "BOH/Characters/BOHUnit.h"
#include "BOH/Controllers/BOHPlayerController.h"
#include "BOH/Messages/BOHGameplayMessage.h"
#include "BOH/Tags/BOHGameplayTagCollection.h"

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHVMPlayerUnits::Init(FBOHViewModelInitParams& InitParams)
{
	Super::Init(InitParams);

	OwningPlayerController = InitParams.OwningPlayerController;
	if (!OwningPlayerController)
	{
		return;
	}
	
	UGameplayMessageSubsystem& GameplayMessageSubsystem = UGameplayMessageSubsystem::Get(OwningPlayerController);

	OnUnitSelectedMessageListenerHandle = GameplayMessageSubsystem.RegisterListener<
		FBOHSelectedUnitMessage>(UBOHGameplayTagCollection::Get().Tag_MessageChannel_UnitSelected, this,
		                         &ThisClass::OnUnitSelected);

	if (ABOHUnit* NewSelectedUnit = OwningPlayerController->GetSelectedUnit())
	{
		SetSelectedUnit(NewSelectedUnit);
	}
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHVMPlayerUnits::Deinit() const
{
	if (UWorld* World = OwningPlayerController ? OwningPlayerController->GetWorld() : nullptr)
	{
		UGameplayMessageSubsystem& GameplayMessageSubsystem = UGameplayMessageSubsystem::Get(World);
		if (OnUnitSelectedMessageListenerHandle.IsValid())
		{
			GameplayMessageSubsystem.UnregisterListener(OnUnitSelectedMessageListenerHandle);
		}	
	}

	Super::Deinit();
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHVMPlayerUnits::OnUnitSelected(FGameplayTag GameplayTag, const FBOHSelectedUnitMessage& SelectedUnitMessage)
{
	if (SelectedUnitMessage.PlayerController != OwningPlayerController)
	{
		return;
	}

	SetSelectedUnit(SelectedUnitMessage.Unit);
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHVMPlayerUnits::SetSelectedUnit(ABOHUnit* InUnit)
{
	SelectedUnit = InUnit;
	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetIsUnitSelected);

	if (!SelectedUnit) { return; }

	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetUnitID);
	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetTeamID);
	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetUnitType);
	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetSpeed);
	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetEvasionRadius);
	UE_MVVM_BROADCAST_FIELD_VALUE_CHANGED(GetReachRadius);
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

bool UBOHVMPlayerUnits::GetIsUnitSelected() const
{
	return SelectedUnit != nullptr;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

int32 UBOHVMPlayerUnits::GetUnitID() const
{
	return SelectedUnit ? SelectedUnit->GetUnitInfo().UnitID : -1;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

int32 UBOHVMPlayerUnits::GetTeamID() const
{
	return SelectedUnit ? SelectedUnit->GetUnitInfo().TeamID : -1;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

EBOHUnitType UBOHVMPlayerUnits::GetUnitType() const
{
	return SelectedUnit ? SelectedUnit->GetUnitInfo().UnitType : EBOHUnitType::None;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

float UBOHVMPlayerUnits::GetSpeed() const
{
	return SelectedUnit ? SelectedUnit->GetUnitInfo().Speed : 0.f;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

float UBOHVMPlayerUnits::GetEvasionRadius() const
{
	return SelectedUnit ? SelectedUnit->GetUnitInfo().EvasionRadius : 0.f;
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

float UBOHVMPlayerUnits::GetReachRadius() const
{
	return SelectedUnit ? SelectedUnit->GetUnitInfo().ReachRadius : 0.f;
}

