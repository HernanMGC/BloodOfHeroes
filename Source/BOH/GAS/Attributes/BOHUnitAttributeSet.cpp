////////////////////////////////////////////////////////////////////////////////////

UBOHUnitAttributeSet::UBOHUnitAttributeSet() : Speed(0.f), ReachRadius(0.f), EvasionRadius(0.f)
{
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHUnitAttributeSet::GetLifetimeReplicatedProps(TArray<FLifetimeProperty>& OutLifetimeProps) const
{
	Super::GetLifetimeReplicatedProps(OutLifetimeProps);

	DOREPLIFETIME_CONDITION_NOTIFY(UBOHUnitAttributeSet, Speed, COND_None, REPNOTIFY_Always);
	DOREPLIFETIME_CONDITION_NOTIFY(UBOHUnitAttributeSet, ReachRadius, COND_None, REPNOTIFY_Always);
	DOREPLIFETIME_CONDITION_NOTIFY(UBOHUnitAttributeSet, EvasionRadius, COND_None, REPNOTIFY_Always);
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHUnitAttributeSet::ClampAttributeOnChange(const FGameplayAttribute& Attribute, float& NewValue) const
{
	if (
		Attribute == GetSpeedAttribute()
		|| Attribute == GetReachRadiusAttribute()
		|| Attribute == GetEvasionRadiusAttribute()
	)
	{
		NewValue = FMath::Clamp(NewValue, 0.f, NewValue);
	}
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHUnitAttributeSet::OnRep_Speed(const FGameplayAttributeData& OldSpeed)
{
	GAMEPLAYATTRIBUTE_REPNOTIFY(UBOHUnitAttributeSet, Speed, OldSpeed);
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHUnitAttributeSet::OnRep_ReachRadius(const FGameplayAttributeData& OldReachRadius)
{
	GAMEPLAYATTRIBUTE_REPNOTIFY(UBOHUnitAttributeSet, ReachRadius, OldReachRadius);
}

////////////////////////////////////////////////////////////////////////////////////
//
////////////////////////////////////////////////////////////////////////////////////

void UBOHUnitAttributeSet::OnRep_EvasionRadius(const FGameplayAttributeData& OldEvasionRadius)
{
	GAMEPLAYATTRIBUTE_REPNOTIFY(UBOHUnitAttributeSet, EvasionRadius, OldEvasionRadius);
}

