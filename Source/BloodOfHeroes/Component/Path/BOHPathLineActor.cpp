void ABOHPathLineActor::SetLineLength(float LineLength, float TotalLineLength)
{
	FVector Scale = StaticMeshComponent->GetComponentScale();	
	Scale.X = LineLength;
	StaticMeshComponent->SetWorldScale3D(Scale);
	OnLineLengthChanged(LineLength, TotalLineLength);
}

